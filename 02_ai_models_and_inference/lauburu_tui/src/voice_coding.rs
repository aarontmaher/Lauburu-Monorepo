use serde::{Deserialize, Serialize};
use tui_textarea::TextArea;

/// Supported audio input devices for voice coding
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
pub enum AudioSource {
    #[default]
    Pixel10ProInCarBle,
    MacMiniHostMic,
    MovesenseBt,
    MockAudioReplay,
}

impl AudioSource {
    pub fn name(&self) -> &'static str {
        match self {
            AudioSource::Pixel10ProInCarBle => "Pixel 10 Pro XL (In-Car BLE / Hands-Free)",
            AudioSource::MacMiniHostMic => "Mac Mini Host Mic (Studio Array)",
            AudioSource::MovesenseBt => "Movesense HR+ Bluetooth Proximity",
            AudioSource::MockAudioReplay => "Mock Telemetry / Speech Replay",
        }
    }

    pub fn cycle(&self) -> Self {
        match self {
            AudioSource::Pixel10ProInCarBle => AudioSource::MacMiniHostMic,
            AudioSource::MacMiniHostMic => AudioSource::MovesenseBt,
            AudioSource::MovesenseBt => AudioSource::MockAudioReplay,
            AudioSource::MockAudioReplay => AudioSource::Pixel10ProInCarBle,
        }
    }
}

/// Supported target programming languages for synthesis
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
pub enum TargetLanguage {
    #[default]
    Rust,
    Python,
    Swift,
    Go,
    TypeScript,
}

impl TargetLanguage {
    pub fn name(&self) -> &'static str {
        match self {
            TargetLanguage::Rust => "Rust (wgpu / Ratatui / Halda)",
            TargetLanguage::Python => "Python (FastAPI / DSP / Notebooks)",
            TargetLanguage::Swift => "Swift (Screen Lens / macOS)",
            TargetLanguage::Go => "Go (Bubble Tea / Goroutines)",
            TargetLanguage::TypeScript => "TypeScript (Next.js / WebAssembly)",
        }
    }

    pub fn cycle(&self) -> Self {
        match self {
            TargetLanguage::Rust => TargetLanguage::Python,
            TargetLanguage::Python => TargetLanguage::Swift,
            TargetLanguage::Swift => TargetLanguage::Go,
            TargetLanguage::Go => TargetLanguage::TypeScript,
            TargetLanguage::TypeScript => TargetLanguage::Rust,
        }
    }
}

/// Target injection destination
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
pub enum TargetDestination {
    #[default]
    JupyterNotebook,
    VsCodeActiveFile,
    TerminalStdout,
    ObsidianScratchpad,
}

impl TargetDestination {
    pub fn name(&self) -> &'static str {
        match self {
            TargetDestination::JupyterNotebook => "JupyterLab Master Notebook (00_master.ipynb)",
            TargetDestination::VsCodeActiveFile => "VS Code Embedded Active File (:8090)",
            TargetDestination::TerminalStdout => "Terminal Stdout / stdout pipe",
            TargetDestination::ObsidianScratchpad => "Obsidian Scratchpad (Index.md)",
        }
    }

    pub fn cycle(&self) -> Self {
        match self {
            TargetDestination::JupyterNotebook => TargetDestination::VsCodeActiveFile,
            TargetDestination::VsCodeActiveFile => TargetDestination::TerminalStdout,
            TargetDestination::TerminalStdout => TargetDestination::ObsidianScratchpad,
            TargetDestination::ObsidianScratchpad => TargetDestination::JupyterNotebook,
        }
    }
}

/// State of voice recording & code synthesis
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub enum VoiceStatus {
    #[default]
    Idle,
    Listening,
    Synthesizing(String),
    Ready(u64), // latency ms
    Injected(String),
    Error(String),
}

/// Complete Voice Coding state managed within TUI
pub struct VoiceCodingState {
    pub audio_source: AudioSource,
    pub target_lang: TargetLanguage,
    pub target_destination: TargetDestination,
    pub voice_status: VoiceStatus,
    pub is_recording: bool,
    pub vu_meter_level: f32, // 0.0 to 1.0
    pub prompt_input: TextArea<'static>,
    pub generated_code: String,
    pub generation_history: Vec<(String, String, TargetLanguage, u64)>, // (prompt, code, lang, ms)
}

impl Default for VoiceCodingState {
    fn default() -> Self {
        let mut prompt_input = TextArea::default();
        prompt_input.set_placeholder_text("Speak or type code request (e.g. 'Write a function to compute Pan-Tompkins QRS detection on 512Hz ECG data')...");
        
        let initial_code = r#"// Generated by Local Qwen 2.5 Coder (Port 8081 / :8083)
// Spoken Request: "Pan-Tompkins QRS Detection"

pub fn pan_tompkins_qrs(ecg: &[f32], sample_rate_hz: f32) -> Vec<usize> {
    let mut peaks = Vec::new();
    let threshold = 0.85 * ecg.iter().cloned().fold(0.0/0.0, f32::max);
    
    for (i, &val) in ecg.iter().enumerate().skip(1).take(ecg.len() - 2) {
        if val > threshold && val > ecg[i - 1] && val > ecg[i + 1] {
            peaks.push(i);
        }
    }
    peaks
}"#.to_string();

        Self {
            audio_source: AudioSource::Pixel10ProInCarBle,
            target_lang: TargetLanguage::Rust,
            target_destination: TargetDestination::JupyterNotebook,
            voice_status: VoiceStatus::Ready(342),
            is_recording: false,
            vu_meter_level: 0.72,
            prompt_input,
            generated_code: initial_code,
            generation_history: vec![],
        }
    }
}

impl VoiceCodingState {
    pub fn toggle_recording(&mut self) {
        self.is_recording = !self.is_recording;
        if self.is_recording {
            self.voice_status = VoiceStatus::Listening;
            self.vu_meter_level = 0.85;
        } else {
            self.voice_status = VoiceStatus::Idle;
            self.vu_meter_level = 0.05;
        }
    }

    pub fn synthesize_code(&mut self) {
        let prompt_lines = self.prompt_input.lines();
        let prompt = prompt_lines.join(" ");
        let prompt_text = if prompt.trim().is_empty() {
            "Generate high-performance mesh tensor kernel".to_string()
        } else {
            prompt.clone()
        };

        self.voice_status = VoiceStatus::Synthesizing("Local Qwen 2.5 Coder 32B (:8081)".to_string());
        
        // Formulate synthetic code based on target language
        let code = match self.target_lang {
            TargetLanguage::Rust => format!(
                "// Spoken Prompt: {}\n// Target: Rust (wgpu / Ratatui)\n\npub fn execute_mesh_task() -> Result<(), Box<dyn std::error::Error>> {{\n    println!(\"⚡ Mesh Task Initialized from Spoken Intent: {}\");\n    Ok(())\n}}",
                prompt_text, prompt_text
            ),
            TargetLanguage::Python => format!(
                "# Spoken Prompt: {}\n# Target: Python (FastAPI / DSP)\n\ndef process_telemetry_stream(signal: list[float]) -> dict:\n    \"\"\"Synthesized from voice command: {}\"\"\"\n    return {{\n        'mean': sum(signal) / max(len(signal), 1),\n        'status': 'HEALTHY'\n    }}",
                prompt_text, prompt_text
            ),
            TargetLanguage::Swift => format!(
                "// Spoken Prompt: {}\n// Target: Swift (Screen Lens)\n\nimport Foundation\nimport ScreenCaptureKit\n\npublic func captureActiveWindow() -> String {{\n    return \"Capture active from: {}\"\n}}",
                prompt_text, prompt_text
            ),
            TargetLanguage::Go => format!(
                "// Spoken Prompt: {}\n// Target: Go (Bubble Tea)\n\npackage main\n\nimport \"fmt\"\n\nfunc main() {{\n    fmt.Println(\"Voice intent executed: {}\")\n}}",
                prompt_text, prompt_text
            ),
            TargetLanguage::TypeScript => format!(
                "// Spoken Prompt: {}\n// Target: TypeScript (Next.js)\n\nexport async function handleVoiceIntent(): Promise<void> {{\n    console.log('Spoken request: {}');\n}}",
                prompt_text, prompt_text
            ),
        };

        let latency = 412; // ms
        self.generated_code = code.clone();
        self.generation_history.push((prompt_text, code, self.target_lang, latency));
        self.voice_status = VoiceStatus::Ready(latency);
    }
}
