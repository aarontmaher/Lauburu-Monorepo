"""
empirical_checker.py - Empirical truth auditing for AI-generated claims.

This module provides classes for empirically verifying claims made by AI models
against physical evidence such as file system state, command execution results,
and network connectivity.
"""

from __future__ import annotations

import os
import subprocess
import hashlib
from enum import Enum
from dataclasses import dataclass, field
from typing import Dict, List, Any, Optional


class ClaimType(Enum):
    """Types of empirical claims that can be audited."""
    FILE_EXISTS = "file_exists"
    FILE_PATH = "file_path"
    FILE_CONTENT = "file_content"
    COMMAND_EXECUTION = "command_execution"
    NETWORK_CONNECTIVITY = "network_connectivity"
    CODE_CORRECTNESS = "code_correctness"
    SYSTEM_STATE = "system_state"
    UNKNOWN = "unknown"


@dataclass
class EvidenceResult:
    """Result of empirical evidence verification."""
    claim: Claim
    is_verified: bool
    evidence_type: str
    details: Dict[str, Any] = field(default_factory=dict)


@dataclass
class Claim:
    """Represents a single empirical claim made by an AI model."""
    claim_id: str
    claim_type: ClaimType
    content: str = ""
    target: str = ""
    pattern_or_content: Optional[str] = None
    agent_id: str = "ai_model"
    source: str = "ai_model"
    verified: bool = False
    verification_result: Optional[str] = None
    evidence: Dict[str, Any] = field(default_factory=dict)

    @property
    def get_target(self) -> str:
        """Return the target path or content to verify."""
        return self.target or self.content


class EmpiricalChecker:
    """
    Empirically audits claims generated by AI models against physical reality.

    Verifies claims by checking file system state, executing commands,
    testing network connectivity, and validating code correctness.
    """

    def __init__(self):
        self.audit_history: List[Claim] = []

    def verify_evidence(self, claim: Claim) -> EvidenceResult:
        """Verify a claim against empirical evidence and return an EvidenceResult."""
        target = claim.get_target
        evidence_type = "unknown"
        is_verified = False
        details: Dict[str, Any] = {}

        try:
            if claim.claim_type in (ClaimType.FILE_EXISTS, ClaimType.FILE_PATH):
                evidence_type = "file_system"
                is_verified = os.path.exists(target)
                details["path"] = target
                details["status"] = "EXISTS" if is_verified else "NOT_FOUND"
                if is_verified and claim.pattern_or_content:
                    if os.path.isfile(target):
                        with open(target, "r", encoding="utf-8", errors="ignore") as f:
                            content = f.read(4096)
                        details["pattern_found"] = claim.pattern_or_content in content

            elif claim.claim_type == ClaimType.FILE_CONTENT:
                evidence_type = "file_content"
                if os.path.isfile(target):
                    with open(target, "r", encoding="utf-8", errors="ignore") as f:
                        content = f.read(8192)
                    is_verified = claim.pattern_or_content is None or claim.pattern_or_content in content
                    details["content_length"] = len(content)

            elif claim.claim_type == ClaimType.COMMAND_EXECUTION:
                evidence_type = "command_execution"
                result = subprocess.run(
                    target, shell=True, capture_output=True, text=True, timeout=10
                )
                is_verified = result.returncode == 0
                details["exit_code"] = result.returncode
                details["stdout"] = result.stdout.strip()[:500]
                details["stderr"] = result.stderr.strip()[:500]

            elif claim.claim_type == ClaimType.NETWORK_CONNECTIVITY:
                evidence_type = "network_connectivity"
                import socket
                parts = target.split(":")
                host = parts[0]
                port = int(parts[1]) if len(parts) > 1 else 80
                with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
                    s.settimeout(2)
                    is_verified = s.connect_ex((host, port)) == 0
                details["host"] = host
                details["port"] = port
                details["status"] = "REACHABLE" if is_verified else "UNREACHABLE"

            else:
                evidence_type = "unknown"
                is_verified = False
                details["reason"] = "Unsupported claim type"

        except Exception as e:
            is_verified = False
            details["error"] = str(e)

        claim.verified = is_verified
        claim.verification_result = evidence_type
        self.audit_history.append(claim)

        return EvidenceResult(
            claim=claim,
            is_verified=is_verified,
            evidence_type=evidence_type,
            details=details
        )

    def verify_claim(self, claim: Claim) -> Claim:
        """Verify a single claim against empirical evidence (legacy API)."""
        result = self.verify_evidence(claim)
        return claim

    def verify_claims(self, claims: List[Claim]) -> List[Claim]:
        """Verify multiple claims and return the results."""
        return [self.verify_claim(claim) for claim in claims]

    def get_audit_summary(self) -> Dict[str, Any]:
        """Return a summary of all audits performed."""
        total = len(self.audit_history)
        verified = sum(1 for c in self.audit_history if c.verified)
        return {
            "total_claims": total,
            "verified": verified,
            "failed": total - verified,
            "verification_rate": round(verified / total, 3) if total > 0 else 0.0,
        }
