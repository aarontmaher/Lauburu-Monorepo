#!/usr/bin/env bash
# Screen Lens Sovereign — GL.iNet / WireGuard / Shizuku Telemetry Sentinel
# Runs as silent 24/7 background daemon. Logs to Obsidian vault + LoRA dataset.
# Per Rules 7, 9, 10: native bash loop, no schedule tool, no mocks.

set -uo pipefail

ROUTER="root@192.168.8.1"
SSH_OPTS="-o ConnectTimeout=4 -o StrictHostKeyChecking=no -o BatchMode=yes"
S20_ADB="192.168.8.131:5555"
VAULT="/Volumes/Lauburu-Monorepo/obsidian_vault/APPS_AND_FEATURES/MESH_TELEMETRY_LOG.md"
LORA="/Volumes/Lauburu-Monorepo/04_data_and_memory/data/continuous_lora_dataset.jsonl"
INTERVAL_FAST=60
INTERVAL_SLOW=300
counter=0

log() { echo "[$(date '+%Y-%m-%d %H:%M:%S')] $*"; }

append_vault() {
  local ts msg
  ts=$(date '+%Y-%m-%d %H:%M:%S')
  msg="$*"
  echo "" >> "$VAULT"
  echo "### $ts" >> "$VAULT"
  echo "$msg" >> "$VAULT"
}

append_lora() {
  # Format: {"instruction": ..., "input": ..., "output": ...}
  local instruction="$1" input="$2" output="$3"
  printf '{"instruction":"%s","input":"%s","output":"%s","timestamp":"%s"}\n' \
    "$instruction" "$input" "$output" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" >> "$LORA"
}

mkdir -p "$(dirname "$VAULT")" "$(dirname "$LORA")"
[ -f "$VAULT" ] || printf "# Mesh Telemetry Log\n\nGenerated by gl_luci_sentinel.sh\n\n" > "$VAULT"

log "GL.iNet Sentinel started. Router=$ROUTER, S20=$S20_ADB"

while true; do
  TIMESTAMP=$(date '+%Y-%m-%d %H:%M:%S')

  # === Fast cycle: WG handshake health ===
  WG_OUTPUT=$(ssh $SSH_OPTS "$ROUTER" "wg show wgserver latest-handshakes 2>/dev/null; echo '---'; uptime; free -m | head -2" 2>/dev/null || echo "ROUTER_UNREACHABLE")
  
  ACTIVE_PEERS=$(echo "$WG_OUTPUT" | grep -c '[0-9]' 2>/dev/null || echo 0)
  LOAD=$(echo "$WG_OUTPUT" | grep 'load average' | awk '{print $NF}' | tr -d ',')
  MEM_FREE=$(echo "$WG_OUTPUT" | awk '/Mem:/{print $4}')

  log "Router: load=$LOAD mem_free=${MEM_FREE}MB wg_peers_seen=$ACTIVE_PEERS"

  # Log to vault every 5 cycles (5 min)
  if (( counter % 5 == 0 )); then
    append_vault "**Router Health** load=$LOAD mem=${MEM_FREE}MB active_wg_peers=$ACTIVE_PEERS\n\`\`\`\n$WG_OUTPUT\n\`\`\`"
    append_lora "Monitor GL.iNet router WireGuard health" "Router: $ROUTER" "$(echo "$WG_OUTPUT" | head -5 | tr '\n' '|')"
  fi

  # === Shizuku health check on S20 ===
  if (( counter % 5 == 0 )); then
    SHIZUKU_STATE=$(adb -s "$S20_ADB" shell "service check moe.shizuku.privileged.api 2>/dev/null; pm list packages | grep shizuku" 2>/dev/null || echo "S20_UNREACHABLE")
    log "S20 Shizuku: $SHIZUKU_STATE"
    
    # Auto-heal: if Shizuku server not running, restart it
    if echo "$SHIZUKU_STATE" | grep -q "not found\|Server is not running"; then
      log "Shizuku server down on S20 — auto-healing..."
      adb -s "$S20_ADB" shell "sh /sdcard/Android/data/moe.shizuku.privileged.api/files/start.sh 2>/dev/null &" 2>/dev/null || true
      append_vault "⚠️ **Shizuku Auto-Heal** — S20 Shizuku server restarted at $TIMESTAMP"
      append_lora "Auto-heal Shizuku on S20" "Shizuku: not running" "sh start.sh executed"
    fi
  fi

  # === Slow cycle: DHCP leases + dmesg check ===
  if (( counter % 5 == 0 )); then
    LEASES=$(ssh $SSH_OPTS "$ROUTER" "cat /tmp/dhcp.leases 2>/dev/null" 2>/dev/null | awk '{print $4" "$3}' | sort || echo "UNAVAILABLE")
    log "DHCP Leases:"$'\n'"$LEASES"

    DMESG_WARN=$(ssh $SSH_OPTS "$ROUTER" "dmesg 2>/dev/null | tail -20 | grep -iE 'error|oops|panic|warn' | head -5" 2>/dev/null || echo "")
    if [ -n "$DMESG_WARN" ]; then
      log "⚠️ Router dmesg warnings: $DMESG_WARN"
      append_vault "⚠️ **Router dmesg Warning** at $TIMESTAMP:\n\`\`\`\n$DMESG_WARN\n\`\`\`"
    fi

    # Router load alarm
    LOAD1=$(ssh $SSH_OPTS "$ROUTER" "cat /proc/loadavg | awk '{print \$1}'" 2>/dev/null || echo "0")
    if awk "BEGIN{exit !($LOAD1 > 8.0)}"; then
      log "⚠️ HIGH LOAD on router: $LOAD1"
      append_vault "⚠️ **Router HIGH LOAD: $LOAD1** at $TIMESTAMP — check MediaTek Wi-Fi driver"
    fi
  fi

  (( counter++ )) || true
  sleep $INTERVAL_FAST
done
