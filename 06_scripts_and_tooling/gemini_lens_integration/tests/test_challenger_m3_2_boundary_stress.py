class TestCliBoundaryAndDryRun:
    """CLI boundary execution and dry-run disk mutation verification."""

    def test_cli_dry_run_exit_code_zero_and_pure_json(self):
        """Verifies python3 notebook_sync.py --dry-run returns exit code 0 and emits pure JSON on stdout."""
        script = Path(__file__).resolve().parent.parent / "notebook_sync.py"
        cmd = ["/opt/homebrew/bin/python3", str(script), "--dry-run"]
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=10.0)

        assert proc.returncode == 0, f"CLI exited with {proc.returncode}. Stderr: {proc.stderr}"
        stdout_text = proc.stdout.strip()
        assert stdout_text.startswith("{")
        assert stdout_text.endswith("}")

        parsed = json.loads(stdout_text)
        assert parsed["status"] == "success"
        assert parsed["dry_run"] is True
        assert parsed["notebook_modified"] is False
        assert parsed["metadata_modified"] is False

    def test_cli_dry_run_zero_disk_mutations(self):
        """Cryptographic SHA256 proof: --dry-run performs zero mutations to existing notebook on disk."""
        script = Path(__file__).resolve().parent.parent / "notebook_sync.py"
        repo_root = Path(__file__).resolve().parent.parent.parent.parent
        target_nb = repo_root / "lens_global_orchestrator.ipynb"

        if not target_nb.exists():
            pytest.skip("lens_global_orchestrator.ipynb does not exist at repo root")

        sha_before = hashlib.sha256(target_nb.read_bytes()).hexdigest()

        cmd = ["/opt/homebrew/bin/python3", str(script), "--dry-run"]
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=10.0)
        assert proc.returncode == 0

        sha_after = hashlib.sha256(target_nb.read_bytes()).hexdigest()
        assert sha_before == sha_after, "Target notebook was mutated on disk during --dry-run execution!"


