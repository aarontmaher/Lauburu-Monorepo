        sanctuary_ok = bool(mem_info.get("sanctuary_preserved", free_gb >= self.min_ram_sanctuary_gb))
        pressure_level = int(mem_info.get("memory_pressure_level", 1))

        remote_url = self.resolve_jupyter_settings_url()

        # Decision rules per Rule 3 Host Sanctuary Invariant
        reasons: List[str] = []

        if force_offload:
            reasons.append("Forced offload requested")
        if free_gb < self.min_ram_sanctuary_gb:
            reasons.append(f"Host free RAM ({free_gb:.2f} GB) is below 4.8 GB sanctuary floor")
        if not sanctuary_ok:
            reasons.append("Host sanctuary condition violated")
        if estimated_task_ram_gb > 0.0 and (free_gb - estimated_task_ram_gb) < self.min_ram_sanctuary_gb:
            reasons.append(
                f"Headroom after estimated task ({(free_gb - estimated_task_ram_gb):.2f} GB) would breach sanctuary floor"
            )
        if pressure_level >= 2:
            reasons.append(f"Mach VM pressure level ({pressure_level}) is elevated")

        should_offload = (
            force_offload
            or (free_gb < self.min_ram_sanctuary_gb)
            or (not sanctuary_ok)
            or (estimated_task_ram_gb > 0.0 and (free_gb - estimated_task_ram_gb) < self.min_ram_sanctuary_gb)
            or (pressure_level >= 2)
        )

        if should_offload:
            colab_status = "RECOMMENDED"
            target_runtime = "Google Colab Tesla T4"
            if mesh_exhausted:
                reasons.append("Peripheral Mesh exhausted; overflowing to Google Colab T4")
