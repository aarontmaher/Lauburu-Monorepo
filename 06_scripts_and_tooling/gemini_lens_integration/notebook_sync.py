    def prune_duplicate_sync_cells(
        self, cells: List[Dict[str, Any]], canonical_idx: Optional[int] = None
    ) -> List[Dict[str, Any]]:
        """Prunes secondary duplicate sync cells matching SYNC_TAG or SYNC_HEADER_PREFIX.

        Retains exactly one canonical sync cell at canonical_idx (or first matching cell),
        preserving all other user cells, metadata, outputs, and execution counts.
        """
        if not cells:
            return []

        target_idx = (
            canonical_idx
            if canonical_idx is not None
            else self._find_sync_cell_index(cells)
        )
        if target_idx is None or target_idx >= len(cells):
            return list(cells)

        pruned: List[Dict[str, Any]] = []
        for idx, cell in enumerate(cells):
            if idx == target_idx:
                pruned.append(cell)
                continue
            if self._is_sync_cell(cell):
                continue
            pruned.append(cell)
        return pruned

