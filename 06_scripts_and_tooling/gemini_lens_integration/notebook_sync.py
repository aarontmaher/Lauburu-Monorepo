    def _atomic_write_json(self, target_path: Path, data: Dict[str, Any], indent: int = 1) -> None:
        """Atomically serializes data to JSON using NamedTemporaryFile in the parent directory.

        Ensures file permissions (0o644) are preserved and eliminates race conditions with PyCharm fsnotifier.
        """
        target_path.parent.mkdir(parents=True, exist_ok=True)
        orig_mode = 0o644
        if target_path.exists():
            try:
                orig_mode = target_path.stat().st_mode & 0o777
            except Exception:
                pass

        temp_file = tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            dir=str(target_path.parent),
            prefix=f".{target_path.name}.",
            suffix=".tmp",
            delete=False,
        )
        temp_path = Path(temp_file.name)
        try:
            os.chmod(temp_path, orig_mode)
            json.dump(data, temp_file, indent=indent, ensure_ascii=False)
            temp_file.write("\n")
            temp_file.flush()
            os.fsync(temp_file.fileno())
            temp_file.close()
            os.replace(str(temp_path), str(target_path))
        finally:
            if temp_path.exists():
                try:
                    temp_path.unlink()
                except OSError:
                    pass

