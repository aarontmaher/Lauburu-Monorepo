def _bypass_proxy_opener() -> urllib.request.OpenerDirector:
    """Builds a urllib opener that explicitly bypasses macOS proxies for localhost."""
    proxy_handler = urllib.request.ProxyHandler({})
    return urllib.request.build_opener(proxy_handler)


def probe_darwin_mach_memory() -> Dict[str, Any]:
    """Authentically probes macOS Mach kernel memory metrics via sysctl and vm_stat.

    Implements Activity Monitor standard formulas from Rule 1 Section 6:
    - App Memory = max(0, (anonymous_pages - purgeable_pages) * page_size)
    - Wired Memory = wired_pages * page_size
    - Compressed = occupied_by_compressor * page_size
    - Cached Files = (file_backed_pages + purgeable_pages) * page_size
    - Memory Used = App Memory + Wired Memory + Compressed
    - Memory Pressure = kern.memorystatus_vm_pressure_level (1=Normal, 2=Warning, 3=Critical)
    """
    if sys.platform != "darwin":
        # Fallback for Linux CI / test runners
        mem_total_gb = 24.0
        mem_free_gb = 8.0
        try:
            if os.path.exists("/proc/meminfo"):
                meminfo: Dict[str, int] = {}
                with open("/proc/meminfo", "r", encoding="utf-8") as f:
                    for line in f:
                        parts = line.split(":")
                        if len(parts) == 2:
                            k = parts[0].strip()
                            v = parts[1].strip().split()[0]
                            try:
                                meminfo[k] = int(v) * 1024
                            except ValueError:
                                pass
                if "MemTotal" in meminfo:
                    mem_total_gb = round(meminfo["MemTotal"] / (1024**3), 2)
                if "MemAvailable" in meminfo:
                    mem_free_gb = round(meminfo["MemAvailable"] / (1024**3), 2)
                elif "MemFree" in meminfo:
                    mem_free_gb = round(meminfo["MemFree"] / (1024**3), 2)
        except Exception:
            pass

        return {
            "total_ram_gb": mem_total_gb,
            "free_ram_gb": mem_free_gb,
            "free_gb": mem_free_gb,
            "wired_gb": 0.0,
            "active_gb": 0.0,
            "inactive_gb": 0.0,
            "compressed_gb": 0.0,
            "memory_pressure_level": 1,
            "sanctuary_floor_gb": DEFAULT_MIN_RAM_SANCTUARY_GB,
            "sanctuary_preserved": mem_free_gb >= DEFAULT_MIN_RAM_SANCTUARY_GB,
            "platform": sys.platform,
        }

    try:
        # Determine page size (typically 16384 bytes on Apple Silicon M4)
        page_size = 16384
        try:
            res_ps = subprocess.run(["sysctl", "-n", "hw.pagesize"], capture_output=True, text=True, timeout=1.0)
            if res_ps.returncode == 0 and res_ps.stdout.strip():
                page_size = int(res_ps.stdout.strip())
        except Exception:
            try:
                page_size = resource.getpagesize()
            except Exception:
                pass

        # Total RAM
        total_ram_bytes = 24 * (1024**3)
        try:
            res_mem = subprocess.run(["sysctl", "-n", "hw.memsize"], capture_output=True, text=True, timeout=1.0)
            if res_mem.returncode == 0 and res_mem.stdout.strip():
                total_ram_bytes = int(res_mem.stdout.strip())
        except Exception:
            pass

        # Memory pressure level
        pressure_level = 1
        try:
            res_press = subprocess.run(
                ["sysctl", "-n", "kern.memorystatus_vm_pressure_level"],
                capture_output=True,
                text=True,
                timeout=1.0,
            )
            if res_press.returncode == 0 and res_press.stdout.strip():
                pressure_level = int(res_press.stdout.strip())
        except Exception:
            pass

        # Parse vm_stat
        out = subprocess.run(["/usr/bin/vm_stat"], capture_output=True, text=True, timeout=1.5)
        pages: Dict[str, int] = {}
        for line in out.stdout.splitlines():
            if ":" in line:
                k, _, v = line.partition(":")
                try:
                    pages[k.strip()] = int(v.strip().rstrip("."))
                except ValueError:
                    pass

        anon_pages = pages.get("Anonymous pages", 0)
        purgeable = pages.get("Pages purgeable", 0)
        wired_pages = pages.get("Pages wired down", 0)
        compressed_pages = pages.get("Pages occupied by compressor", 0)
        file_backed = pages.get("File-backed pages", 0)
        free_pages = pages.get("Pages free", 0)
        inactive_pages = pages.get("Pages inactive", 0)
        active_pages = pages.get("Pages active", 0)

        app_mem_bytes = max(0, (anon_pages - purgeable) * page_size)
        wired_bytes = wired_pages * page_size
        compressed_bytes = compressed_pages * page_size
        cached_files_bytes = (file_backed + purgeable) * page_size
        used_mem_bytes = app_mem_bytes + wired_bytes + compressed_bytes
        free_bytes = max(0, total_ram_bytes - used_mem_bytes)

        # Standard free calculation (or raw free pages)
        free_gb = round(free_bytes / (1024**3), 2)
        total_gb = round(total_ram_bytes / (1024**3), 2)
        wired_gb = round(wired_bytes / (1024**3), 2)
        active_gb = round((active_pages * page_size) / (1024**3), 2)
        inactive_gb = round((inactive_pages * page_size) / (1024**3), 2)
        compressed_gb = round(compressed_bytes / (1024**3), 2)

        sanctuary_preserved = (free_gb >= DEFAULT_MIN_RAM_SANCTUARY_GB) and (pressure_level <= 1)

        return {
            "total_ram_gb": total_gb,
            "free_ram_gb": free_gb,
            "free_gb": free_gb,
            "wired_gb": wired_gb,
            "active_gb": active_gb,
            "inactive_gb": inactive_gb,
            "compressed_gb": compressed_gb,
            "memory_pressure_level": pressure_level,
            "sanctuary_floor_gb": DEFAULT_MIN_RAM_SANCTUARY_GB,
            "sanctuary_preserved": sanctuary_preserved,
            "platform": "darwin",
        }
    except Exception as exc:
        logger.debug(f"Darwin Mach probe error: {exc}")
        return {
            "total_ram_gb": 24.0,
            "free_ram_gb": 0.0,
            "free_gb": 0.0,
            "wired_gb": 0.0,
            "active_gb": 0.0,
            "inactive_gb": 0.0,
            "compressed_gb": 0.0,
            "memory_pressure_level": 2,
            "sanctuary_floor_gb": DEFAULT_MIN_RAM_SANCTUARY_GB,
            "sanctuary_preserved": False,
            "platform": "darwin",
            "error": str(exc),
        }


class NotebookSynchronizer:
    """Orchestrates bidirectional synchronization between Screen Lens telemetry and PyCharm."""

    def __init__(
        self,
        config_path: Optional[Union[str, Path]] = None,
        config_dict: Optional[Dict[str, Any]] = None,
        notebook_path: Optional[Union[str, Path]] = None,
        metadata_path: Optional[Union[str, Path]] = None,
        repo_root: Optional[Union[str, Path]] = None,
        min_ram_sanctuary_gb: Optional[float] = None,
        options_dir: Optional[Union[str, Path]] = None,
        prune_duplicates: bool = False,
    ) -> None:
        """Initializes synchronizer with configuration and resolved file paths."""
        if repo_root:
            self.repo_root = Path(repo_root).resolve()
        else:
            default_root = Path(DEFAULT_REPO_ROOT)
            if default_root.exists():
                self.repo_root = default_root.resolve()
            else:
                # Fallback to current project root's parent/grandparent
                self.repo_root = Path(__file__).resolve().parent.parent.parent

        self.config = self._load_config(config_path, config_dict)

        resilience_cfg = self.config.get("resilience", {})
        self.min_ram_sanctuary_gb = float(
            min_ram_sanctuary_gb
            or resilience_cfg.get("min_ram_sanctuary_gb")
            or DEFAULT_MIN_RAM_SANCTUARY_GB
        )

        ide_cfg = self.config.get("ide_integration", {})
        self.pycharm_port = int(ide_cfg.get("pycharm_port", DEFAULT_PYCHARM_PORT))

        self.prune_duplicates = bool(
            prune_duplicates or ide_cfg.get("prune_duplicates", False)
        )

        configured_options = ide_cfg.get("options_dir")
        if options_dir:
            self.options_dir = Path(options_dir).resolve()
        elif configured_options:
            self.options_dir = Path(configured_options).resolve()
        else:
            self.options_dir = None

        configured_nb = ide_cfg.get("notebook_target_path")
        if notebook_path:
            self.notebook_path = self._resolve_project_path(notebook_path, DEFAULT_TARGET_NOTEBOOK)
        elif configured_nb:
            self.notebook_path = self._resolve_project_path(configured_nb, DEFAULT_TARGET_NOTEBOOK)
        else:
            self.notebook_path = (self.repo_root / DEFAULT_TARGET_NOTEBOOK).resolve()

        configured_meta = ide_cfg.get("metadata_path")
        if metadata_path:
            self.metadata_path = self._resolve_project_path(metadata_path, DEFAULT_METADATA_REL)
        elif configured_meta:
            self.metadata_path = self._resolve_project_path(configured_meta, DEFAULT_METADATA_REL)
        else:
            self.metadata_path = (self.repo_root / DEFAULT_METADATA_REL).resolve()

        self.idea_dir = self.metadata_path.parent
        self.jupyter_settings_path = self.idea_dir / "jupyter-settings.xml"

    def _resolve_project_path(
        self, path: Union[str, Path, None], default_rel: str
    ) -> Path:
        """Resolves project paths across heterogeneous nodes (L1 Mac Mini, L5 MacBook Air)."""
        if not path:
            return (self.repo_root / default_rel).resolve()

        raw_str = str(path).strip()
        expanded = Path(os.path.expanduser(raw_str))
        if expanded.exists():
            return expanded.resolve()

        if "Lauburu-Monorepo/" in raw_str:
            rel = raw_str.split("Lauburu-Monorepo/", 1)[1]
            candidate = (self.repo_root / rel).resolve()
            if candidate.exists() or self.repo_root.exists():
                return candidate

        if not expanded.is_absolute():
            return (self.repo_root / raw_str).resolve()

        try:
            expanded.parent.mkdir(parents=True, exist_ok=True)
            return expanded.resolve()
        except (PermissionError, OSError):
            return (self.repo_root / expanded.name).resolve()

    def _load_config(
        self, config_path: Optional[Union[str, Path]], config_dict: Optional[Dict[str, Any]]
    ) -> Dict[str, Any]:
        """Loads configuration dictionary from passed arguments or default path."""
        if config_dict is not None:
            return json.loads(json.dumps(config_dict))

        target_path: Optional[Path] = None
        if config_path:
            target_path = Path(config_path).resolve()
        else:
            # Check standard relative location
            default_loc = Path(__file__).resolve().parent / "config" / "sync_config.json"
            if default_loc.exists():
                target_path = default_loc

        if target_path and target_path.exists():
            try:
                with open(target_path, "r", encoding="utf-8") as f:
                    return json.load(f)
            except Exception as exc:
                logger.warning(f"Failed to parse config file at {target_path}: {exc}")

        # Baseline minimal fallback configuration
        return {
            "resilience": {
                "min_ram_sanctuary_gb": DEFAULT_MIN_RAM_SANCTUARY_GB
            },
            "ide_integration": {
                "pycharm_port": DEFAULT_PYCHARM_PORT,
                "notebook_target_path": str(self.repo_root / DEFAULT_TARGET_NOTEBOOK),
                "metadata_path": str(self.repo_root / DEFAULT_METADATA_REL),
            },
        }

    def detect_pycharm_workspace(
        self,
        options_dir: Optional[Union[str, Path]] = None,
        port: Optional[int] = None,
    ) -> Dict[str, Any]:
        """Resiliently probes PyCharm environment across 4 tiers:

        Tier 1: Live process table (pgrep / psutil) and built-in webserver on port 63342.
        Tier 2: recentProjects.xml registry for opened="true" project and projectWorkspaceId.
        Tier 3: workspace/{projectWorkspaceId}.xml for active open files and notebook tabs.
        Tier 4: Offline graceful fallback without raising unhandled exceptions.
        """
        port = port if port is not None else self.pycharm_port
        default_workspace = str(self.repo_root)
        default_open_file = self.notebook_path.name

        is_running = False
        pid: Optional[int] = None
        fsnotifier_pid: Optional[int] = None
        pycharm_build: Optional[str] = None
        source = "fallback"

        # Tier 1: Process probe
        try:
            import psutil
            for p in psutil.process_iter(["pid", "name", "cmdline"]):
                cmd = " ".join(p.info["cmdline"] or []).lower()
                name = (p.info["name"] or "").lower()
                if "contents/macos/pycharm" in cmd or name == "pycharm":
                    is_running = True
                    pid = p.info["pid"]
                elif "fsnotifier" in cmd or name == "fsnotifier":
                    fsnotifier_pid = p.info["pid"]
        except Exception:
            try:
                res_py = subprocess.run(["pgrep", "-f", "pycharm"], capture_output=True, text=True, timeout=1.0)
                if res_py.returncode == 0 and res_py.stdout.strip():
                    is_running = True
                    pids = res_py.stdout.strip().splitlines()
                    pid = int(pids[0]) if pids else None
                res_fs = subprocess.run(["pgrep", "-f", "fsnotifier"], capture_output=True, text=True, timeout=1.0)
                if res_fs.returncode == 0 and res_fs.stdout.strip():
                    fs_pids = res_fs.stdout.strip().splitlines()
                    fsnotifier_pid = int(fs_pids[0]) if fs_pids else None
            except Exception:
                pass

        # Probe port 63342 API
        if is_running or not is_running:
            # We attempt port probe even if pgrep was inconclusive (e.g. sandboxed runner)
            try:
                opener = _bypass_proxy_opener()
                req = urllib.request.Request(
                    f"http://127.0.0.1:{port}/api/about",
                    headers={"User-Agent": "GeminiLensSync/1.0"},
                )
                with opener.open(req, timeout=1.2) as resp:
                    if resp.status == 200:
                        data = json.loads(resp.read().decode("utf-8"))
                        bn = data.get("buildNumber")
                        if bn:
                            pycharm_build = f"PY-{bn}"
                        elif data.get("name"):
                            pycharm_build = data.get("name")
                        is_running = True
                        source = "live_api"
            except Exception:
                pass

        # Tier 2: Recent projects XML registry
        target_opt = options_dir if options_dir else self.options_dir
        options_dir_provided = target_opt is not None
        resolved_options_dir: Optional[Path] = (
            Path(target_opt).resolve() if target_opt else None
        )

        if not options_dir_provided:
            base_jb = Path(os.path.expanduser("~/Library/Application Support/JetBrains"))
            if base_jb.exists():
                candidates = sorted(
                    base_jb.glob("PyCharm*/options"),
                    key=lambda p: p.stat().st_mtime,
                    reverse=True,
                )
                if candidates:
                    resolved_options_dir = candidates[0]

        recent_xml: Optional[Path] = None
        if resolved_options_dir:
            if (resolved_options_dir / "recentProjects.xml").exists():
                recent_xml = resolved_options_dir / "recentProjects.xml"
            elif (resolved_options_dir.parent / "options" / "recentProjects.xml").exists():
                recent_xml = resolved_options_dir.parent / "options" / "recentProjects.xml"

        active_workspace = default_workspace
        workspace_id: Optional[str] = None
        open_files: List[str] = []
        active_tab: Optional[str] = default_open_file

        if recent_xml and recent_xml.exists():
            try:
                tree = ET.parse(recent_xml)
                root = tree.getroot()
                opened_entry: Optional[Tuple[str, Optional[ET.Element]]] = None

                for entry in root.findall('.//component[@name="RecentProjectsManager"]//entry'):
                    meta = entry.find("value/RecentProjectMetaInfo")
                    if meta is not None and meta.attrib.get("opened") == "true":
                        opened_entry = (entry.attrib.get("key", ""), meta)
                        break

                if not opened_entry:
                    last_opened = root.find('.//option[@name="lastOpenedProject"]')
                    if last_opened is not None:
                        last_path = last_opened.attrib.get("value", "")
                        for entry in root.findall('.//component[@name="RecentProjectsManager"]//entry'):
                            if entry.attrib.get("key") == last_path:
                                opened_entry = (last_path, entry.find("value/RecentProjectMetaInfo"))
                                break

                if opened_entry:
                    raw_path, meta = opened_entry
                    cleaned = raw_path.replace("$USER_HOME$", os.path.expanduser("~"))
                    cleaned = os.path.expanduser(cleaned)

                    # Project matching: Check if opened project matches self.repo_root
                    is_project_match = True
                    if self.repo_root and cleaned:
                        try:
                            target_repo = Path(self.repo_root).resolve()
                            cleaned_path = Path(cleaned).resolve()
                            if target_repo == cleaned_path:
                                is_project_match = True
                            elif target_repo.exists() and cleaned_path.exists():
                                is_project_match = target_repo.samefile(cleaned_path)
                            else:
                                is_project_match = False
                        except Exception:
                            is_project_match = False

                    if is_project_match:
                        active_workspace = default_workspace
                    else:
                        active_workspace = cleaned if options_dir_provided else default_workspace

                    if meta is not None:
                        # If project does not match self.repo_root and options_dir was not explicitly provided,
                        # do NOT adopt the foreign project's projectWorkspaceId
                        if is_project_match or options_dir_provided:
                            workspace_id = meta.attrib.get("projectWorkspaceId")
                        else:
                            workspace_id = None
                        if not pycharm_build:
                            # 1. Child option tag: <option name="build" value="PY-262.10968.92" />
                            opt_build = meta.find(".//option[@name='build']")
                            if opt_build is not None and opt_build.attrib.get("value"):
                                pycharm_build = opt_build.attrib.get("value")
                            elif meta.attrib.get("build"):
                                # 2. Attribute fallback: <RecentProjectMetaInfo build="PY-..." ...>
                                pycharm_build = meta.attrib.get("build")
                            else:
                                # 3. Direct children iteration defensive safeguard
                                for opt in meta.findall("option"):
                                    if opt.attrib.get("name") == "build" and opt.attrib.get("value"):
                                        pycharm_build = opt.attrib.get("value")
                                        break

                    if source == "fallback":
                        source = "options_xml"
            except Exception as exc:
                logger.debug(f"XML parse error in {recent_xml}: {exc}")
                # Regex fallback recovery on partially written or corrupt XML
                try:
                    content = recent_xml.read_text(encoding="utf-8")
                    opened_target: Optional[Tuple[str, Optional[str], Optional[str]]] = None

                    # Find all entry blocks
                    entry_matches = list(
                        re.finditer(
                            r"""<entry\s+key=['"]([^'"]+)['"]>(.*?)(?=</entry>|<entry|\Z)""",
                            content,
                            re.DOTALL,
                        )
                    )

                    # 1. Search for entry with opened="true"
                    for em in entry_matches:
                        ekey = em.group(1)
                        ebody = em.group(2)
                        if re.search(r"""opened=['"]true['"]""", ebody):
                            ws_m = re.search(r"""projectWorkspaceId=['"]([^'"]+)['"]""", ebody)
                            b_m = (
                                re.search(r"""<option\b[^>]*?\bname=['"]build['"][^>]*?\bvalue=['"]([^'"]+)['"]""", ebody)
                                or re.search(r"""<option\b[^>]*?\bvalue=['"]([^'"]+)['"][^>]*?\bname=['"]build['"]""", ebody)
                                or re.search(r"""\bbuild=['"]([^'"]+)['"]""", ebody)
                            )
                            opened_target = (
                                ekey,
                                ws_m.group(1) if ws_m else None,
                                b_m.group(1) if b_m else None,
                            )
                            break

                    # 2. If no opened="true", check lastOpenedProject
                    if not opened_target:
                        last_m = re.search(
                            r"""<option\s+name=['"]lastOpenedProject['"]\s+value=['"]([^'"]+)['"]""",
                            content,
                        )
                        if last_m:
                            last_path = last_m.group(1)
                            for em in entry_matches:
                                if em.group(1) == last_path:
                                    ebody = em.group(2)
                                    ws_m = re.search(r"""projectWorkspaceId=['"]([^'"]+)['"]""", ebody)
                                    b_m = (
                                        re.search(r"""<option\b[^>]*?\bname=['"]build['"][^>]*?\bvalue=['"]([^'"]+)['"]""", ebody)
                                        or re.search(r"""<option\b[^>]*?\bvalue=['"]([^'"]+)['"][^>]*?\bname=['"]build['"]""", ebody)
                                        or re.search(r"""\bbuild=['"]([^'"]+)['"]""", ebody)
                                    )
                                    opened_target = (
                                        last_path,
                                        ws_m.group(1) if ws_m else None,
                                        b_m.group(1) if b_m else None,
                                    )
                                    break

                    # 3. Fallback to broad regex if entry tags were fragmented
                    if not opened_target:
                        m_key = re.search(r"""entry key=['"]([^'"]+)['"]""", content)
                        m_ws = re.search(r"""projectWorkspaceId=['"]([^'"]+)['"]""", content)
                        m_b = (
                            re.search(r"""<option\b[^>]*?\bname=['"]build['"][^>]*?\bvalue=['"]([^'"]+)['"]""", content)
                            or re.search(r"""<option\b[^>]*?\bvalue=['"]([^'"]+)['"][^>]*?\bname=['"]build['"]""", content)
                            or re.search(r"""\bbuild=['"]([^'"]+)['"]""", content)
                        )
                        if m_key or m_ws:
                            opened_target = (
                                m_key.group(1) if m_key else "",
                                m_ws.group(1) if m_ws else None,
                                m_b.group(1) if m_b else None,
                            )

                    if opened_target:
                        raw_path, ws_id, b_val = opened_target
                        cleaned = raw_path.replace("$USER_HOME$", os.path.expanduser("~")) if raw_path else ""
                        cleaned = os.path.expanduser(cleaned) if cleaned else ""

                        is_project_match = True
                        if self.repo_root and cleaned:
                            try:
                                target_repo = Path(self.repo_root).resolve()
                                cleaned_path = Path(cleaned).resolve()
                                if target_repo == cleaned_path:
                                    is_project_match = True
                                elif target_repo.exists() and cleaned_path.exists():
                                    is_project_match = target_repo.samefile(cleaned_path)
                                else:
                                    is_project_match = False
                            except Exception:
                                is_project_match = False

                        if is_project_match or options_dir_provided:
                            if raw_path:
                                active_workspace = cleaned
                            if ws_id:
                                workspace_id = ws_id
                        else:
                            active_workspace = default_workspace
                            workspace_id = None
                        if b_val and not pycharm_build:
                            pycharm_build = b_val
                        if source == "fallback":
                            source = "options_xml"
                except Exception as regex_exc:
                    logger.debug(f"Regex fallback failed: {regex_exc}")

        # Tier 3: Active Workspace State XML (workspace/<id>.xml)
