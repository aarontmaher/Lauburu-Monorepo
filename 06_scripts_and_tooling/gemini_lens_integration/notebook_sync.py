    def _is_sync_cell(self, cell: Dict[str, Any]) -> bool:
        """Determines whether a notebook cell matches Screen Lens sync indicators."""
        if not isinstance(cell, dict):
            return False
        tags = cell.get("metadata", {}).get("tags", [])
