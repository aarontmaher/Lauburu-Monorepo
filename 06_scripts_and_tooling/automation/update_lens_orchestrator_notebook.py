def make_cell(
    cell_type: str,
    source: str,
    cell_id: Optional[str] = None,
    tags: Optional[List[str]] = None,
) -> Dict[str, Any]:
    lines = [l + "\n" for l in source.splitlines()]
    if lines and not source.endswith("\n"):
        lines[-1] = lines[-1].rstrip("\n")
    meta: Dict[str, Any] = {}
    if tags:
        meta["tags"] = tags
    cell: Dict[str, Any] = {
        "cell_type": cell_type,
        "id": cell_id or str(uuid.uuid4())[:8],
        "metadata": meta,
        "source": lines,
    }
    if cell_type == "code":
        cell["execution_count"] = None
        cell["outputs"] = []
    return cell


