use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum AppDomain {
    ClientHubs,
    Biometrics,
    AiInference,
    TerminalTuis,
    Commerce,
    EdgeMobile,
}

impl AppDomain {
    pub fn all() -> &'static [AppDomain] {
        &[
            AppDomain::ClientHubs,
            AppDomain::Biometrics,
            AppDomain::AiInference,
            AppDomain::TerminalTuis,
            AppDomain::Commerce,
            AppDomain::EdgeMobile,
        ]
    }

    pub fn title(&self) -> &'static str {
        match self {
            AppDomain::ClientHubs => "🚀 1. Client Hubs & Web Portals",
            AppDomain::Biometrics => "🩺 2. Biometrics DSP & Kinematics",
            AppDomain::AiInference => "🧠 3. AI Inference, PRP Ring & Training",
            AppDomain::TerminalTuis => "🖥️ 4. Terminal TUIs & Workbenches",
            AppDomain::Commerce => "🛍️ 5. Commerce & Subscriptions",
            AppDomain::EdgeMobile => "📱 6. Edge Mobile & Reverse Eng",
        }
    }

    pub fn short_name(&self) -> &'static str {
        match self {
            AppDomain::ClientHubs => "Client Hubs",
            AppDomain::Biometrics => "Biometrics",
            AppDomain::AiInference => "AI & Training",
            AppDomain::TerminalTuis => "Terminal TUIs",
            AppDomain::Commerce => "Commerce",
            AppDomain::EdgeMobile => "Edge & Mobile",
        }
    }

    pub fn description(&self) -> &'static str {
        match self {
            AppDomain::ClientHubs => "Production end-user web applications, Flutter desktop interfaces, and unified routers.",
            AppDomain::Biometrics => "Medical-grade 512Hz Pan-Tompkins ECG, PTT blood pressure, and 3D spatial kinematics tatami.",
            AppDomain::AiInference => "Prima.cpp PRP ring masters, local GGUF sharding, AI combat arenas, and 24/7 LoRA harvesters.",
            AppDomain::TerminalTuis => "High-performance Rust Ratatui/Go/Python TUIs, JupyterLab, Marimo, and Voilà analytical studios.",
            AppDomain::Commerce => "Shopify Storefront GraphQL APIs, multi-tier subscription billing ($0/$19/$99/mo), and token redemptions.",
            AppDomain::EdgeMobile => "Vision-language-action Screen Lens, Termux edge daemons, APK reverse engineering, and cable analyzer.",
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AppEntry {
    pub id: &'static str,
    pub name: &'static str,
    pub domain: AppDomain,
    pub path: &'static str,
    pub tech_stack: Vec<&'static str>,
    pub port: Option<u16>,
    pub url: Option<&'static str>,
    pub launch_cmd: &'static str,
    pub test_cmd: &'static str,
    pub description: &'static str,
    pub icon: &'static str,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct AppLiveStatus {
    pub is_running: bool,
    pub pid: Option<u32>,
    pub cpu_pct: Option<f32>,
    pub rss_mb: Option<f32>,
    pub port_online: bool,
    pub rtt_ms: Option<f64>,
    pub status_label: String,
}

