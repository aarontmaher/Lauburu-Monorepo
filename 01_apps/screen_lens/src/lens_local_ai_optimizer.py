def get_ram_info():
    # macOS specific: check vm_stat to estimate free RAM.
    try:
        vm = subprocess.run(["vm_stat"], capture_output=True, text=True).stdout
        pages_free = 0
        pages_inactive = 0
        for line in vm.split('\n'):
            if "Pages free" in line:
                pages_free = int(line.split(':')[1].strip().strip('.'))
            elif "Pages inactive" in line:
                pages_inactive = int(line.split(':')[1].strip().strip('.'))
        
        # 1 page = 16384 bytes on M4/Apple Silicon (16KB pages)
        free_gb = (pages_free + pages_inactive) * 16384 / (1024**3)
        return free_gb
    except:
        return 12.0 # fallback

