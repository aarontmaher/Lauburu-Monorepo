    def __init__(self):
        self.pro_tokens_budget_weekly = 1000000
        self.pro_tokens_consumed = 0
        self.max_tokens_per_pro_call = 4096
        self.history = []

    def evaluate_task_for_escalation(
        self,
        task_description: str,
        files_involved: List[str] = None,
        prior_failure_count: int = 0
    ) -> Dict[str, Any]:
        """
        Uses Gemini Free Tier logic to evaluate whether a task warrants spending
        precious Google AI Ultra Plan tokens on Gemini 3.1 Pro.
        """
        t0 = time.perf_counter()
        files_involved = files_involved or []
        num_files = len(files_involved)

        # Free tier triage heuristics (empirical complexity score)
        is_cross_repo = any("00_core" in f for f in files_involved) and any("01_apps" in f for f in files_involved)
        is_c11_native = any(f.endswith(".c") or f.endswith(".h") for f in files_involved)
        token_estimate = len(task_description.split()) * 4 + sum(len(f) * 10 for f in files_involved)

        # Baseline confidence generated by Free Tier assessment
        if num_files <= 2 and not is_cross_repo and prior_failure_count == 0:
            confidence = 0.95
            triage_verdict = "RESOLVE_ON_FREE_TIER_OR_LOCAL"
            action_tier = "Tier 0/1: Local Qwen 3.8 Max or Gemini 2.0 Flash Free"
            escalate_to_gemini_pro = False
            rationale = "Task is well-scoped with high local confidence (0.95). Preserves 100% of Google AI Ultra plan tokens."
        elif prior_failure_count >= 2 and (is_cross_repo or is_c11_native):
            confidence = 0.65
            triage_verdict = "ESCALATE_TO_GEMINI_3_1_PRO"
            action_tier = "Tier 3: Google AI Ultra Plan Token Allocation (Gemini 3.1 Pro High)"
            escalate_to_gemini_pro = True
            rationale = (
                f"Multi-attempt stagnation detected ({prior_failure_count} failures) on cross-subsystem task. "
                f"Free Tier confidence dropped to {confidence:.2f} (< 0.85). "
                f"Surgically escalating to Gemini 3.1 Pro High with max 4,096 token envelope."
            )
        elif token_estimate > 32000:
            confidence = 0.78
            triage_verdict = "EVALUATE_ON_FREE_TIER_FIRST"
            action_tier = "Tier 2: Gemini 2.0 Flash 1M Context (Free Tier)"
            escalate_to_gemini_pro = False
            rationale = "High token context, but Gemini 2.0 Flash Free handles 1M context at $0 spend. Trying Free Tier first."
        else:
            confidence = 0.88
            triage_verdict = "RESOLVE_ON_FREE_TIER"
            action_tier = "Tier 2: Gemini 2.0 Flash / NVIDIA DeepSeek Free Tier"
            escalate_to_gemini_pro = False
            rationale = f"Free tier confidence is {confidence:.2f} (>= 0.85). Free tier API sufficient."

        elapsed_us = round((time.perf_counter() - t0) * 1e6, 2)

        decision = {
            "timestamp": time.strftime("%Y-%m-%d %H:%M:%S UTC", time.gmtime()),
            "task_summary": task_description[:120],
            "files_count": num_files,
            "prior_failure_count": prior_failure_count,
            "free_tier_confidence": confidence,
            "triage_verdict": triage_verdict,
            "action_tier": action_tier,
            "escalate_to_gemini_3_1_pro": escalate_to_gemini_pro,
            "pro_token_cap": self.max_tokens_per_pro_call if escalate_to_gemini_pro else 0,
            "plan_tokens_saved_estimate": 8192 if not escalate_to_gemini_pro else 0,
            "rationale": rationale,
            "triage_latency_us": elapsed_us
        }

        self.history.append(decision)
        return decision


