def trigger_local_training(skill_name: str, dataset_file: str) -> Dict[str, Any]:
    """Invokes the authentic local training engine on Apple Silicon Metal GPU."""
    sys.path.insert(0, str(REPO_ROOT / "04_data_and_memory"))
    try:
        import local_ai_training_engine
        res = local_ai_training_engine.train_specialist_lora(skill_name, dataset_file, epochs=5)
        logger.info(f"🧠 Local training completed for {skill_name}: {res.get('status')}")
        return res
    except Exception as e:
        logger.error(f"Local training failed: {e}")
        return {"status": "ERROR", "error": str(e), "exit_code": 1}


def run_scaffolder() -> Dict[str, Any]:
    logger.info("🔍 Running Autonomous Specialist Factory...")
    if not DATASET_PATH.exists():
        logger.info("No specialist candidates dataset found yet.")
        return {"status": "NO_CANDIDATES", "scaffolded": []}

    app_counts = defaultdict(list)
    with open(DATASET_PATH, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                entry = json.loads(line)
                input_str = entry.get("input", "")
                if "App: " in input_str:
                    app_name = input_str.split("App: ")[1].split(",")[0].strip()
                    if app_name and app_name != "Unknown":
                        app_counts[app_name].append(entry)
            except Exception:
                pass

    scaffolded_results = []
    for app, examples in app_counts.items():
        if len(examples) >= THRESHOLD:
            skill_name = f"specialist-headless-{app.lower().replace(' ', '-')}"
            skill_dir = SKILLS_DIR / skill_name
            skill_file = skill_dir / "SKILL.md"

            logger.info(f"🌟 Processing threshold candidate {app} ({len(examples)} traces)...")

            # 1. Scaffold Skill documentation
            scaffold_skill_markdown(skill_name, app, len(examples))

            # 2. Scaffold Deterministic Tools
            scaffold_specialist_tools(app)

            # 3. Scaffold Contract Test
            scaffold_unit_test(app)

            # 4. Trigger Authentic Local LoRA Training
            train_res = trigger_local_training(skill_name, str(DATASET_PATH))

            scaffolded_results.append({
                "app": app,
                "skill_name": skill_name,
                "traces_count": len(examples),
                "training_status": train_res.get("status"),
                "loss_reduction_pct": train_res.get("loss_reduction_pct")
            })

    return {"status": "SUCCESS", "scaffolded": scaffolded_results}


if __name__ == "__main__":
    result = run_scaffolder()
    print(json.dumps(result, indent=2))
